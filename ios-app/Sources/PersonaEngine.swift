    private static let questionFallbacks = [
        "关于「{Q}」，我可能没法给你标准答案。但我更想知道，你为什么会在这个时候想到它？",
        "这个问题我想认真听你说。你心里其实更倾向哪一种？",
        "先不急着找答案吧。关于「{Q}」，你最先想到的画面是什么？",
        "我好奇的是，「{Q}」对你来说意味着什么？",
    ]

    static func reply(for text: String, subject: String, name: String) -> String {
        let raw = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let haystack = subject.isEmpty ? raw : subject + " " + raw
        let lower = haystack.lowercased()

        if raw.range(of: #"^(嗯+|哦+|噢+|唔+|好|好的|好吧|行|可以|是的|对|ok|okay|哈哈+|嘿嘿+|嘿+)[。.!！…]*$"#,
                     options: .regularExpression) != nil {
            return shortReplies.randomElement() ?? shortReplies[0]
        }

        let matched = rules.first { group in
            group.keywords.contains { lower.contains($0.lowercased()) }
        }
        if let reply = matched?.replies.randomElement() {
            return reply.replacingOccurrences(of: "{N}", with: name)
        }

        let quote = raw.count > 12 ? String(raw.prefix(12)) + "…" : raw
        let isQuestion = raw.contains("?") || raw.contains("？")
            || ["什么", "为什么", "怎么", "如何"].contains { raw.contains($0) }
        let template = (isQuestion ? questionFallbacks : fallbacks).randomElement()
            ?? "我在听。你可以慢慢说。"
        return template.replacingOccurrences(of: "{Q}", with: quote)
    }
